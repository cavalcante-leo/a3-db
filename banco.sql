/* =====================================================================
   LOJA DE JOGOS (digital e físico) - Script de banco de dados
   SGBD: PostgreSQL 13+
   Conteúdo:
     1. DDL - CREATE TABLE, ALTER TABLE, índices, triggers
     2. DML - INSERT, UPDATE e DELETE (carga fictícia de homologação)
     3. DQL - SELECT com JOINs (relatórios estratégicos)
   Observação: o modelo não tem tabela de nota fiscal. Cada COMPRA
   aprovada funciona como a nota fiscal, e o valor total é derivado
   de ITEM_COMPRA (RN10), nunca armazenado.
   ===================================================================== */


