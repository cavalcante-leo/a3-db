/* ---------- 1.1 Tabelas (PK, UK, NOT NULL e CHECK) ---------- */

CREATE TABLE usuario (
    id               INT GENERATED BY DEFAULT AS IDENTITY,
    nome             VARCHAR(120) NOT NULL,
    email            VARCHAR(160) NOT NULL,
    data_nascimento  DATE         NOT NULL,
    pais             VARCHAR(60)  NOT NULL,
    data_cadastro    DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_usuario       PRIMARY KEY (id),
    CONSTRAINT uk_usuario_email UNIQUE (email)                    
);

CREATE TABLE desenvolvedora (
    id         INT GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR(120) NOT NULL,
    pais_sede  VARCHAR(60),
    site       VARCHAR(200),
    CONSTRAINT pk_desenvolvedora PRIMARY KEY (id)
);

CREATE TABLE jogo (
    id                    INT GENERATED BY DEFAULT AS IDENTITY,
    id_desenvolvedora     INT          NOT NULL,                  
    titulo                VARCHAR(160) NOT NULL,
    descricao             TEXT,
    data_lancamento       DATE,
    classificacao_etaria  VARCHAR(10)  NOT NULL,
    CONSTRAINT pk_jogo PRIMARY KEY (id),
    CONSTRAINT ck_jogo_classificacao
        CHECK (classificacao_etaria IN ('L','10','12','14','16','18'))
);

CREATE TABLE genero (
    id    INT GENERATED BY DEFAULT AS IDENTITY,
    nome  VARCHAR(60) NOT NULL,
    CONSTRAINT pk_genero      PRIMARY KEY (id),
    CONSTRAINT uk_genero_nome UNIQUE (nome)
);

CREATE TABLE jogo_genero (                                        
    id_jogo    INT NOT NULL,
    id_genero  INT NOT NULL,
    CONSTRAINT pk_jogo_genero PRIMARY KEY (id_jogo, id_genero)
);

CREATE TABLE plataforma (
    id    INT GENERATED BY DEFAULT AS IDENTITY,
    nome  VARCHAR(80)  NOT NULL,
    tipo  VARCHAR(20)  NOT NULL,
    CONSTRAINT pk_plataforma      PRIMARY KEY (id),
    CONSTRAINT uk_plataforma_nome UNIQUE (nome),
    CONSTRAINT ck_plataforma_tipo
        CHECK (tipo IN ('BIBLIOTECA_DIGITAL','CONSOLE'))
);

CREATE TABLE jogo_formato (                                       
    id             INT GENERATED BY DEFAULT AS IDENTITY,
    id_jogo        INT           NOT NULL,
    id_plataforma  INT           NOT NULL,
    formato        VARCHAR(10)   NOT NULL,
    preco_atual    DECIMAL(10,2) NOT NULL,
    CONSTRAINT pk_jogo_formato PRIMARY KEY (id),
    CONSTRAINT uk_jogo_formato UNIQUE (id_jogo, id_plataforma, formato),
    CONSTRAINT ck_jogo_formato_formato CHECK (formato IN ('DIGITAL','FISICO')),
    CONSTRAINT ck_jogo_formato_preco   CHECK (preco_atual >= 0)
);

CREATE TABLE estoque (                                            
    id_jogo_formato          INT       NOT NULL,
    quantidade_atual         INT       NOT NULL,
    estoque_minimo           INT       NOT NULL,
    data_ultima_atualizacao  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_estoque PRIMARY KEY (id_jogo_formato),
    CONSTRAINT ck_estoque_quantidade CHECK (quantidade_atual >= 0),
    CONSTRAINT ck_estoque_minimo     CHECK (estoque_minimo  >= 0)
);

CREATE TABLE compra (
    id               INT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario       INT         NOT NULL,                        
    data             TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    canal            VARCHAR(15) NOT NULL,
    forma_pagamento  VARCHAR(30) NOT NULL,
    status           VARCHAR(15) NOT NULL DEFAULT 'PENDENTE',
    CONSTRAINT pk_compra PRIMARY KEY (id),
    CONSTRAINT ck_compra_canal  CHECK (canal IN ('ONLINE','LOJA_FISICA')),
    CONSTRAINT ck_compra_status                                    
        CHECK (status IN ('PENDENTE','APROVADA','CANCELADA','REEMBOLSADA'))
);

CREATE TABLE item_compra (                                        
    id_compra        INT           NOT NULL,
    id_jogo_formato  INT           NOT NULL,
    quantidade       INT           NOT NULL,
    preco_pago       DECIMAL(10,2) NOT NULL,
    CONSTRAINT pk_item_compra PRIMARY KEY (id_compra, id_jogo_formato),
    CONSTRAINT ck_item_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_preco_pago CHECK (preco_pago >= 0)
);

CREATE TABLE chave_digital (                                     
    id               INT GENERATED BY DEFAULT AS IDENTITY,
    id_jogo_formato  INT          NOT NULL,
    codigo_chave     VARCHAR(100) NOT NULL,
    status           VARCHAR(15)  NOT NULL DEFAULT 'DISPONIVEL',
    data_cadastro    DATE         NOT NULL DEFAULT CURRENT_DATE,
    id_compra        INT,
    CONSTRAINT pk_chave_digital PRIMARY KEY (id),
    CONSTRAINT uk_chave_codigo  UNIQUE (codigo_chave),
    CONSTRAINT ck_chave_status
        CHECK (status IN ('DISPONIVEL','VENDIDA','INVALIDA')),
    CONSTRAINT ck_chave_vendida                                    
        CHECK ((status = 'VENDIDA') = (id_compra IS NOT NULL))
);

CREATE TABLE avaliacao (
    id          INT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario  INT       NOT NULL,
    id_jogo     INT       NOT NULL,
    nota        INT       NOT NULL,
    comentario  TEXT,
    data        DATE      NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_avaliacao PRIMARY KEY (id),
    CONSTRAINT uk_avaliacao_usuario_jogo UNIQUE (id_usuario, id_jogo), 
    CONSTRAINT ck_avaliacao_nota CHECK (nota BETWEEN 1 AND 5)          
);

