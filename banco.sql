/* =====================================================================
   3. DQL - consultas estratégicas
   Regra RN09: os relatórios consideram apenas compras APROVADAS.
   ===================================================================== */

/* ---------- 3.0 View: nota fiscal (cabeçalho) com total derivado ---------- */

CREATE OR REPLACE VIEW vw_nota_fiscal AS
SELECT c.id                              AS numero_nota,
       c.data                            AS data_emissao,
       c.id_usuario,
       u.nome                            AS cliente,
       u.email,
       c.canal,
       c.forma_pagamento,
       c.status,
       SUM(ic.quantidade)                AS qtd_itens,
       SUM(ic.preco_pago * ic.quantidade) AS valor_total
  FROM compra c
  JOIN usuario u       ON u.id = c.id_usuario
  JOIN item_compra ic  ON ic.id_compra = c.id
 GROUP BY c.id, c.data, c.id_usuario, u.nome, u.email,
          c.canal, c.forma_pagamento, c.status;

/* ---------- 3.1 Notas fiscais dos clientes no último mês (cabeçalho) ---------- */

SELECT nf.numero_nota,
       TO_CHAR(nf.data_emissao, 'DD/MM/YYYY HH24:MI') AS data_emissao,
       nf.cliente,
       nf.canal,
       nf.forma_pagamento,
       nf.qtd_itens,
       nf.valor_total
  FROM vw_nota_fiscal nf
 WHERE nf.status = 'APROVADA'
   AND nf.data_emissao >= NOW() - INTERVAL '1 month'
 ORDER BY nf.data_emissao DESC;

/* ---------- 3.2 Notas fiscais do último mês com itens detalhados ---------- */

SELECT c.id                                   AS numero_nota,
       TO_CHAR(c.data, 'DD/MM/YYYY')          AS data_emissao,
       u.nome                                 AS cliente,
       j.titulo                               AS jogo,
       p.nome                                 AS plataforma,
       jf.formato,
       ic.quantidade,
       ic.preco_pago                          AS preco_unitario,
       ic.quantidade * ic.preco_pago          AS subtotal
  FROM compra c
  JOIN usuario u       ON u.id  = c.id_usuario
  JOIN item_compra ic  ON ic.id_compra = c.id
  JOIN jogo_formato jf ON jf.id = ic.id_jogo_formato
  JOIN jogo j          ON j.id  = jf.id_jogo
  JOIN plataforma p    ON p.id  = jf.id_plataforma
 WHERE c.status = 'APROVADA'
   AND c.data >= NOW() - INTERVAL '1 month'
 ORDER BY c.data DESC, c.id, j.titulo;

/* ---------- 3.3 Faturamento do último mês por canal e forma de pagamento ---------- */

SELECT nf.canal,
       nf.forma_pagamento,
       COUNT(*)                    AS qtd_notas,
       SUM(nf.valor_total)         AS faturamento,
       ROUND(AVG(nf.valor_total), 2) AS ticket_medio
  FROM vw_nota_fiscal nf
 WHERE nf.status = 'APROVADA'
   AND nf.data_emissao >= NOW() - INTERVAL '1 month'
 GROUP BY nf.canal, nf.forma_pagamento
 ORDER BY faturamento DESC;

/* ---------- 3.4 Jogos mais vendidos e receita (todas as compras aprovadas) ---------- */

SELECT j.titulo,
       d.nome                          AS desenvolvedora,
       SUM(ic.quantidade)              AS unidades_vendidas,
       SUM(ic.quantidade * ic.preco_pago) AS receita
  FROM item_compra ic
  JOIN compra c        ON c.id  = ic.id_compra
  JOIN jogo_formato jf ON jf.id = ic.id_jogo_formato
  JOIN jogo j          ON j.id  = jf.id_jogo
  JOIN desenvolvedora d ON d.id = j.id_desenvolvedora
 WHERE c.status = 'APROVADA'
 GROUP BY j.id, j.titulo, d.nome
 ORDER BY unidades_vendidas DESC, receita DESC;

/* ---------- 3.5 Ranking de clientes por gasto (função de janela) ---------- */

SELECT RANK() OVER (ORDER BY SUM(nf.valor_total) DESC) AS posicao,
       nf.cliente,
       COUNT(*)                 AS qtd_notas,
       SUM(nf.valor_total)      AS total_gasto
  FROM vw_nota_fiscal nf
 WHERE nf.status = 'APROVADA'
 GROUP BY nf.id_usuario, nf.cliente
 ORDER BY posicao;

/* ---------- 3.6 Relatório de reposição de estoque (RN14) ---------- */

SELECT j.titulo,
       p.nome                              AS plataforma,
       e.quantidade_atual,
       e.estoque_minimo,
       e.estoque_minimo - e.quantidade_atual AS faltante,
       e.data_ultima_atualizacao
  FROM estoque e
  JOIN jogo_formato jf ON jf.id = e.id_jogo_formato
  JOIN jogo j          ON j.id  = jf.id_jogo
  JOIN plataforma p    ON p.id  = jf.id_plataforma
 WHERE e.quantidade_atual <= e.estoque_minimo
 ORDER BY faltante DESC;

/* ---------- 3.7 Disponibilidade de chaves digitais por jogo ---------- */

SELECT j.titulo,
       p.nome                                         AS plataforma,
       COUNT(cd.id)                                   AS total_chaves,
       COUNT(cd.id) FILTER (WHERE cd.status = 'DISPONIVEL') AS disponiveis,
       COUNT(cd.id) FILTER (WHERE cd.status = 'VENDIDA')    AS vendidas
  FROM jogo_formato jf
  JOIN jogo j       ON j.id = jf.id_jogo
  JOIN plataforma p ON p.id = jf.id_plataforma
  LEFT JOIN chave_digital cd ON cd.id_jogo_formato = jf.id
 WHERE jf.formato = 'DIGITAL'
 GROUP BY j.titulo, p.nome
 ORDER BY disponiveis ASC, j.titulo;

/* ---------- 3.8 Nota média e quantidade de avaliações por jogo ---------- */

SELECT j.titulo,
       COUNT(a.id)                    AS qtd_avaliacoes,
       ROUND(AVG(a.nota), 2)          AS nota_media
  FROM jogo j
  LEFT JOIN avaliacao a ON a.id_jogo = j.id
 GROUP BY j.id, j.titulo
 ORDER BY nota_media DESC NULLS LAST, qtd_avaliacoes DESC;

/* ---------- 3.9 Gêneros mais vendidos (N:N via jogo_genero) ---------- */

SELECT g.nome                         AS genero,
       SUM(ic.quantidade)             AS unidades_vendidas
  FROM genero g
  JOIN jogo_genero jg  ON jg.id_genero = g.id
  JOIN jogo_formato jf ON jf.id_jogo   = jg.id_jogo
  JOIN item_compra ic  ON ic.id_jogo_formato = jf.id
  JOIN compra c        ON c.id = ic.id_compra
 WHERE c.status = 'APROVADA'
 GROUP BY g.id, g.nome
 ORDER BY unidades_vendidas DESC;

/* ---------- 3.10 Auditoria de idade: compras acima da classificação etária ---------- */

SELECT c.id                                   AS numero_nota,
       u.nome                                 AS cliente,
       EXTRACT(YEAR FROM AGE(c.data, u.data_nascimento))::INT AS idade_na_compra,
       j.titulo,
       j.classificacao_etaria
  FROM compra c
  JOIN usuario u       ON u.id  = c.id_usuario
  JOIN item_compra ic  ON ic.id_compra = c.id
  JOIN jogo_formato jf ON jf.id = ic.id_jogo_formato
  JOIN jogo j          ON j.id  = jf.id_jogo
 WHERE c.status = 'APROVADA'
   AND j.classificacao_etaria <> 'L'
   AND EXTRACT(YEAR FROM AGE(c.data, u.data_nascimento)) < j.classificacao_etaria::INT;

/* ---------- 3.11 Auditoria: avaliações de quem não comprou o jogo ---------- */

SELECT a.id AS id_avaliacao,
       u.nome AS cliente,
       j.titulo
  FROM avaliacao a
  JOIN usuario u ON u.id = a.id_usuario
  JOIN jogo j    ON j.id = a.id_jogo
 WHERE NOT EXISTS (
        SELECT 1
          FROM compra c
          JOIN item_compra ic  ON ic.id_compra = c.id
          JOIN jogo_formato jf ON jf.id = ic.id_jogo_formato
         WHERE c.id_usuario = a.id_usuario
           AND jf.id_jogo   = a.id_jogo
           AND c.status     = 'APROVADA'
       );

/* ---------- 3.12 Rastreio: chaves vendidas por nota fiscal ---------- */

SELECT c.id        AS numero_nota,
       u.nome      AS cliente,
       j.titulo,
       cd.codigo_chave
  FROM chave_digital cd
  JOIN item_compra ic  ON ic.id_compra = cd.id_compra
                      AND ic.id_jogo_formato = cd.id_jogo_formato
  JOIN compra c        ON c.id  = ic.id_compra
  JOIN usuario u       ON u.id  = c.id_usuario
  JOIN jogo_formato jf ON jf.id = cd.id_jogo_formato
  JOIN jogo j          ON j.id  = jf.id_jogo
 WHERE cd.status = 'VENDIDA'
 ORDER BY c.id, j.titulo;